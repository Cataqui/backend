import { createTestBindings, Jpeg } from "../../test/fakes";
import { GeoimageError } from "../geoimage.error";
import { ImageGenerationDurableObject } from "./image-generation.durable-object";

const _params = {
	key: "maps/v1/test.jpg",
	requestId: "owned",
	map: { center: { latitude: 0, longitude: 0 }, size: { width: 480, height: 480 }, density: 2 },
} as const;
let _bindings: ReturnType<typeof createTestBindings>;
let _object: ImageGenerationDurableObject;
async function _generate(): Promise<Response> {
	const result = await _object.generate(_params);
	if ("errorCode" in result) throw new GeoimageError(result.errorCode);
	return result.response;
}
const _fetch = vi.fn<typeof fetch>();
beforeEach(() => {
	_bindings = createTestBindings();
	_object = new ImageGenerationDurableObject({} as DurableObjectState, _bindings.env);
	vi.stubGlobal("fetch", _fetch);
});
afterEach(() => {
	vi.unstubAllGlobals();
	vi.restoreAllMocks();
	_fetch.mockReset();
});

it("rechecks R2 inside the coordinator and streams a raced storage hit without Geoapify", async () => {
	_bindings.objects.set(_params.key, Jpeg);
	const response = await _generate();
	expect(new Uint8Array(await response.arrayBuffer())).toEqual(Jpeg);
	expect(_fetch).not.toHaveBeenCalled();
});
it("reports storage unavailable if the object disappears during its recheck", async () => {
	_bindings.get
		.mockResolvedValueOnce({ body: new Response(Jpeg).body!, httpEtag: '"etag"', size: Jpeg.length } as R2ObjectBody)
		.mockResolvedValueOnce(null);
	await expect(_generate()).rejects.toMatchObject({ errorCode: "STORAGE_UNAVAILABLE" });
	expect(_fetch).not.toHaveBeenCalled();
});
it("does not return generated bytes until their complete body and storage attempt finish", async () => {
	let controller: ReadableStreamDefaultController<Uint8Array> | undefined;
	const stream = new ReadableStream<Uint8Array>({
		start(value) {
			controller = value;
		},
	});
	_fetch.mockResolvedValue(new Response(stream, { headers: { "Content-Type": "image/jpeg" } }));
	let returned = false;
	const pending = _generate().then((response) => {
		returned = true;
		return response;
	});
	await vi.waitFor(() => expect(_fetch).toHaveBeenCalledTimes(1));
	controller!.enqueue(Jpeg.slice(0, 2));
	await Promise.resolve();
	expect(returned).toBe(false);
	expect(_bindings.put).not.toHaveBeenCalled();
	controller!.enqueue(Jpeg.slice(2));
	controller!.close();
	expect(new Uint8Array(await (await pending).arrayBuffer())).toEqual(Jpeg);
	expect(_bindings.put).toHaveBeenCalledTimes(1);
});
it("cancels provider bodies above 8 MiB without storing or returning partial bytes", async () => {
	const cancel = vi.fn();
	const stream = new ReadableStream<Uint8Array>({
		start(controller) {
			controller.enqueue(new Uint8Array(8 * 1024 * 1024));
			controller.enqueue(new Uint8Array(1));
		},
		cancel: cancel,
	});
	_fetch.mockResolvedValue(new Response(stream, { headers: { "Content-Type": "image/jpeg" } }));
	await expect(_generate()).rejects.toMatchObject({ errorCode: "PROVIDER_UNAVAILABLE" });
	expect(cancel).toHaveBeenCalledTimes(1);
	expect(_bindings.put).not.toHaveBeenCalled();
});
it("rejects an empty image stream", async () => {
	_fetch.mockResolvedValue(new Response(new Uint8Array(), { headers: { "Content-Type": "image/jpeg" } }));
	await expect(_generate()).rejects.toMatchObject({ errorCode: "PROVIDER_UNAVAILABLE" });
	expect(_bindings.put).not.toHaveBeenCalled();
});
it.each([
	new Error("private"),
	new DOMException("private", "NetworkError"),
	new DOMException("private", "TimeoutError"),
	new DOMException("private", "AbortError"),
])("sanitizes failures while reading the provider body: %s", async (error) => {
	_fetch.mockResolvedValue(
		new Response(
			new ReadableStream({
				start(controller) {
					controller.error(error);
				},
			}),
			{ headers: { "Content-Type": "image/jpeg" } },
		),
	);
	await expect(_generate()).rejects.toMatchObject({
		errorCode:
			error instanceof DOMException && ["TimeoutError", "AbortError"].includes(error.name)
				? "PROVIDER_TIMEOUT"
				: "PROVIDER_UNAVAILABLE",
	});
	expect(_bindings.put).not.toHaveBeenCalled();
});
it("returns bytes when R2 put returns no stored object", async () => {
	const log = vi.spyOn(console, "error").mockImplementation(() => {});
	_bindings.put.mockResolvedValue(null as unknown as R2Object);
	_fetch.mockResolvedValue(new Response(Jpeg, { headers: { "Content-Type": "image/jpeg" } }));
	const response = await _generate();
	expect(new Uint8Array(await response.arrayBuffer())).toEqual(Jpeg);
	expect(response.headers.get("ETag")).toBeNull();
	expect(log).toHaveBeenCalledExactlyOnceWith({ event: "geoimage.storage.write.failed", requestId: "owned" });
});
